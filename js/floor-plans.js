// Floor 4 reuses the floor 3 plan, but DPRO only has 3 floors, so any shape whose
// center falls inside the DPRO footprint is left out. The DPRO outline is read from
// campus-geojson.js, so this stays correct if the floor 3 shapes are edited.
const floor4Data = (() => {
  // Find the DPRO building outline.
  const dpro = geojsonData.features.find(
    (f) => f.properties && f.properties.DPRO,
  );
  const ring = dpro.geometry.coordinates[0];

  // Point-in-polygon test (ray casting): is the point inside the DPRO outline?
  const inside = (x, y) => {
    let hit = false;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (
        yi > y !== yj > y &&
        x < ((xj - xi) * (y - yi)) / (yj - yi) + xi
      )
        hit = !hit;
    }
    return hit;
  };

  // Average of a shape's corner points, used as its center.
  const center = (g) => {
    const pts = g.type === "Polygon" ? g.coordinates[0] : g.coordinates;
    return [
      pts.reduce((s, c) => s + c[0], 0) / pts.length,
      pts.reduce((s, c) => s + c[1], 0) / pts.length,
    ];
  };

  // Floor 3's shapes, minus any whose center is inside DPRO.
  return {
    type: "FeatureCollection",
    features: floor3Data.features.filter(
      (f) => !inside(...center(f.geometry)),
    ),
  };
})();
